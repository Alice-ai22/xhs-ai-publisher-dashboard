/**
 * 根据模板类型获取模板配置
 */
export function getTemplate(type: ContentType): ContentTemplate {
  const template = CONTENT_TEMPLATES.find((t) => t.type === type);
  if (!template) {
    throw new Error(`未知的内容模板类型: ${type}`);
  }
  return template;
}

/**
 * 获取所有模板类型列表（用于 UI 下拉框）
 */
export function getTemplateOptions(): Array<{
  value: ContentType;
  label: string;
  description: string;
}> {
  return CONTENT_TEMPLATES.map((t) => ({
    value: t.type,
    label: t.label,
    description: t.description,
  }));
}
